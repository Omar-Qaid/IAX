/// <summary>
/// Settle and post sales tax. Tax posted to the input and output tax accounts as documents were
/// invoiced and nothing ever cleared them, so those accounts only grew. Settlement clears each tax
/// account for a period interval and moves the net to the sales tax settlement account.
///
/// Signs follow the posting convention: TaxTrans.TaxAmount carries the ledger entry's sign, so
/// incoming (input) tax is positive and outgoing (payable) tax is negative.
/// </summary>
public class TaxSettlementTests
{
    private const string Area = "dat";

    [Fact]
    public async Task Settlement_clears_both_tax_accounts_and_moves_the_net_to_the_settlement_account()
    {
        await using var connection = new SqliteConnection("Data Source=:memory:");
        await connection.OpenAsync();
        await using var db = await NewContextAsync(connection);
        // Output tax 1,500 collected (credit) and input tax 400 paid (debit): net 1,100 payable.
        AddTax(db, 1, "VAT-OUT", TaxDirection.Outgoing, new DateTime(2026, 6, 5), -1000m);
        AddTax(db, 2, "VAT-OUT", TaxDirection.Outgoing, new DateTime(2026, 6, 20), -500m);
        AddTax(db, 3, "VAT-IN", TaxDirection.Incoming, new DateTime(2026, 6, 12), 400m);
        await db.SaveChangesAsync();
        db.ChangeTracker.Clear();

        var (result, error) = await NewService(db).SettleAndPostAsync(
            new TaxSettlementInputDto("MONTHLY", new DateOnly(2026, 6, 1), new DateOnly(2026, 6, 30)), default);

        Assert.Null(error);
        Assert.NotNull(result);
        Assert.Equal(3, result!.TaxTransactionCount);
        Assert.Equal(-1500m, result.OutgoingTaxCleared);
        Assert.Equal(400m, result.IncomingTaxCleared);
        Assert.Equal(-1100m, result.SettlementAmount);
        Assert.Equal(1, result.VersionNum);

        // The voucher balances, which is the point: clearing each account plus the settlement line.
        var lines = await db.Set<GeneralJournalAccountEntry>().AsNoTracking().ToListAsync();
        Assert.Equal(0m, lines.Sum(x => x.AccountingCurrencyAmount));
        Assert.All(lines, x => Assert.Equal(LedgerPostingType.Tax, x.PostingType));

        // Output tax account is debited 1,500 to clear its credit balance; input tax credited 400.
        Assert.Equal(1500m, lines.Single(x => x.LedgerAccount == "210300").AccountingCurrencyAmount);
        Assert.Equal(-400m, lines.Single(x => x.LedgerAccount == "140300").AccountingCurrencyAmount);
        // The net lands on the settlement account as a credit: this is what is owed.
        Assert.Equal(-1100m, lines.Single(x => x.LedgerAccount == "210900").AccountingCurrencyAmount);

        // Every settled transaction is stamped, and an offsetting transaction is posted for each.
        var settled = await db.Set<TaxTrans>().AsNoTracking().Where(x => x.OrigTaxTransRecId == 0).ToListAsync();
        Assert.All(settled, x => Assert.Equal("MONTHLY", x.TaxPeriod));
        Assert.All(settled, x => Assert.Equal(1, x.TaxRepCounter));
        var offsets = await db.Set<TaxTrans>().AsNoTracking().Where(x => x.OrigTaxTransRecId != 0).ToListAsync();
        Assert.Equal(3, offsets.Count);
        // Offsets negate the originals, so posted tax nets to zero in the tax inquiry too.
        Assert.Equal(0m, settled.Sum(x => x.TaxAmount) + offsets.Sum(x => x.TaxAmount));
        Assert.All(offsets, x => Assert.Equal(NoYes.Yes, x.TaxAutoGenerated));

        var interval = await db.Set<TaxReportPeriod>().AsNoTracking().SingleAsync();
        Assert.Equal(1, interval.VersionNum);
    }

    [Fact]
    public async Task An_interval_can_only_be_settled_once()
    {
        await using var connection = new SqliteConnection("Data Source=:memory:");
        await connection.OpenAsync();
        await using var db = await NewContextAsync(connection);
        AddTax(db, 1, "VAT-OUT", TaxDirection.Outgoing, new DateTime(2026, 6, 5), -1000m);
        await db.SaveChangesAsync();
        db.ChangeTracker.Clear();

        var input = new TaxSettlementInputDto("MONTHLY", new DateOnly(2026, 6, 1), new DateOnly(2026, 6, 30));
        var (first, firstError) = await NewService(db).SettleAndPostAsync(input, default);
        Assert.Null(firstError);
        Assert.NotNull(first);
        db.ChangeTracker.Clear();

        var (second, error) = await NewService(db).SettleAndPostAsync(input, default);
        Assert.Null(second);
        Assert.Contains("already settled", error);

        // The refused run posted nothing on top of the first, which cleared one tax account and
        // wrote the settlement line.
        Assert.Equal(2, await db.Set<GeneralJournalAccountEntry>().CountAsync());
    }

