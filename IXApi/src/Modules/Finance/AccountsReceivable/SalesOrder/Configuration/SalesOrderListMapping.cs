using IAX.IXApi.Modules.Finance.Entities;
using IAX.IXApi.Modules.Finance.Common;
using Mapster;

namespace IAX.IXApi.Modules.Finance.AccountsReceivable;

public sealed record SalesOrderListMappingSource(SalesTable Order, string CustomerName, string DeliveryAddress);

public sealed class SalesOrderListMapping : IRegister
{
    public void Register(TypeAdapterConfig config)
    {
        config.NewConfig<SalesOrderListMappingSource, SalesOrderListDto>()
            .Map(d => d.RecId, s => s.Order.RecId)
            .Map(d => d.SalesId, s => s.Order.SalesId)
            .Map(d => d.CustomerAccount, s => s.Order.CustAccount)
            .Map(d => d.CustomerName, s => s.CustomerName)
            .Map(d => d.InvoiceAccount, s => s.Order.InvoiceAccount)
            .Map(d => d.CustomerGroup, s => s.Order.CustGroup)
            .Map(d => d.CurrencyCode, s => s.Order.CurrencyCode)
            .Map(d => d.SalesStatus, s => s.Order.SalesStatus.ToString())
            .Map(d => d.DocumentStatus, s => s.Order.DocumentStatus.ToString())
            .Map(d => d.DeliveryDate, s => s.Order.DeliveryDate)
            .Map(d => d.ShippingDateRequested, s => s.Order.ShippingDateRequested)
            .Map(d => d.OrderTotal, s => s.Order.SmmSalesAmountTotal)
            .Map(d => d.CustomerReference, s => s.Order.CustomerRef)
            .Map(d => d.DeliveryMode, s => s.Order.DlvMode)
            .Map(d => d.DeliveryTerms, s => s.Order.DlvTerm)
            .Map(d => d.OrderDate, s => s.Order.OrderDate == default
                ? (s.Order.CreatedAt.HasValue ? s.Order.CreatedAt.Value.Date : default)
                : s.Order.OrderDate)
            .Map(d => d.InventSiteId, s => s.Order.InventSiteId)
            .Map(d => d.InventLocationId, s => s.Order.InventLocationId)
            .Map(d => d.SalesNameAlias, s => s.Order.SalesNameAlias)
            .Map(d => d.SalesType, s => (int)(s.Order.SalesType ?? SalesType.Sales))
            .Map(d => d.OneTimeCustomer, s => s.Order.OneTimeCustomer == NoYes.Yes)
            .Map(d => d.Email, s => s.Order.Email)
            .Map(d => d.Phone, s => s.Order.Phone)
            .Map(d => d.Deadline, s => s.Order.Deadline == default ? (DateTime?)null : s.Order.Deadline)
            .Map(d => d.CustomerRequisitionNumber, s => s.Order.CustRequisitionNum)
            .Map(d => d.CampaignId, s => s.Order.SmmCampaignId)
            .Map(d => d.TaxGroupId, s => s.Order.TaxGroupId)
            .Map(d => d.PricesIncludeSalesTax, s => s.Order.InclTax)
            .Map(d => d.SalesGroup, s => s.Order.SalesGroup)
            .Map(d => d.LanguageId, s => s.Order.LanguageId)
            .Map(d => d.PaymentTerms, s => s.Order.PaymTerm)
            .Map(d => d.DeliveryName, s => s.Order.DeliveryName)
            .Map(d => d.DeliveryPostalAddress, s => s.Order.DeliveryPostalAddress == 0
                ? string.Empty
                : s.Order.DeliveryPostalAddress.ToString(System.Globalization.CultureInfo.InvariantCulture))
            .Map(d => d.DeliveryAddress, s => s.DeliveryAddress)
            .Map(d => d.ShippingDateConfirmed, s => s.Order.ShippingDateConfirmed == default ? (DateTime?)null : s.Order.ShippingDateConfirmed)
            .Map(d => d.ReceiptDateConfirmed, s => s.Order.ReceiptDateConfirmed == default ? (DateTime?)null : s.Order.ReceiptDateConfirmed)
            .Map(d => d.DeliveryDateControlType, s => (int)s.Order.DeliveryDateControlType)
            .Map(d => d.MpsFullRunCtpStatus, s => (int)s.Order.MpsFullRunCtpStatus)
            .Map(d => d.BlindShipment, s => s.Order.ShipCarrierBlindShipment == NoYes.Yes)
            .Map(d => d.ResidentialDestination, s => s.Order.ShipCarrierResidential)
            .Map(d => d.ExcludeFromMasterPlanning, s => s.Order.MpsExcludeSalesOrder)
            .Map(d => d.DeliveryReason, s => s.Order.DlvReason)
            .Map(d => d.ExportReason, s => s.Order.ExportReason)
            .Map(d => d.ShippingCarrier, s => s.Order.ShipCarrierName)
            .Map(d => d.CarrierId, s => s.Order.ShipCarrierId)
            .Map(d => d.CarrierGroup, s => string.Empty)
            .Map(d => d.BrokerId, s => s.Order.ShipCarrierAccountCode)
            .Map(d => d.TransportMode, s => s.Order.Transport)
            .Map(d => d.CarrierService, s => (int)s.Order.ShipCarrierDlvType)
            .Map(d => d.PaymentMethod, s => s.Order.PaymMode)
            .Map(d => d.PaymentSchedule, s => s.Order.PaymentSched)
            .Map(d => d.PaymentSpecification, s => s.Order.PaymSpec)
            .Map(d => d.FixedDueDate, s => s.Order.FixedDueDate == default ? (DateTime?)null : s.Order.FixedDueDate)
            .Map(d => d.PaymentTermsBaseDate, s => s.Order.CashDiscBaseDate == default ? (DateTime?)null : s.Order.CashDiscBaseDate)
            .Map(d => d.CashDiscountCode, s => s.Order.CashDisc)
            .Map(d => d.DiscountPercent, s => s.Order.CashDiscPercent)
            .Map(d => d.TotalDiscountPercent, s => s.Order.DiscPercent)
            .Map(d => d.FixedExchangeRate, s => s.Order.FixedExchRate)
            .Map(d => d.ReportingCurrencyFixedExchangeRate, s => s.Order.ReportingCurrencyFixedExchRate)
            .Map(d => d.PriceGroup, s => s.Order.PriceGroupId)
            .Map(d => d.LineDiscountGroup, s => s.Order.LineDisc)
            .Map(d => d.MultiLineDiscountGroup, s => s.Order.MultiLineDisc)
            .Map(d => d.TotalDiscountGroup, s => s.Order.EndDisc)
            .Map(d => d.ChargesGroup, s => s.Order.MarkupGroup)
            .Map(d => d.CustomerRebateGroup, s => s.Order.PdsCustRebateGroupId)
            .Map(d => d.CustomerTmaGroup, s => s.Order.PdsRebateProgramTmaGroup)
            .Map(d => d.RebateReference, s => s.Order.TamRebateReference)
            .Map(d => d.SalesPool, s => s.Order.SalesPoolId)
            .Map(d => d.CarrierCustomerAccount, s => s.Order.ShipCarrierAccount)
            .Map(d => d.FreightZone, s => s.Order.FreightZone)
            .Map(d => d.Notes, s => s.Order.Notes)
            .Map(d => d.IntercompanyAutoCreateOrders, s => s.Order.IntercompanyAutoCreateOrders)
            .Map(d => d.IntercompanyDirectDelivery, s => s.Order.IntercompanyDirectDelivery)
            .Map(d => d.IntercompanyOrigin, s => (int)s.Order.IntercompanyOrigin)
            .Map(d => d.IntercompanyAllowIndirectCreation, s => s.Order.IntercompanyAllowIndirectCreation)
            .Map(d => d.ReleaseStatus, s => s.Order.ReleaseStatus.ToString())
            .Map(d => d.Reservation, s => (int)s.Order.Reservation);
    }
}
