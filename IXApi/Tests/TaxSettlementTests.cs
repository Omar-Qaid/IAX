    private static ISysNumberSequenceService NewSequences() =>
        DispatchProxy.Create<ISysNumberSequenceService, TaxSequenceProxy>();

    public class TaxSequenceProxy : DispatchProxy
    {
        private int _n;
        protected override object? Invoke(MethodInfo? method, object?[]? args)
        {
            if (method?.Name != nameof(ISysNumberSequenceService.NextAsync))
                throw new NotSupportedException(method?.Name);
            var entity = (string)args![0]!;
            _n++;
            return Task.FromResult(new NextSequenceResultDto
                { EntityName = entity, Value = _n, Code = $"{entity}-{_n:D4}" });
        }
    }

