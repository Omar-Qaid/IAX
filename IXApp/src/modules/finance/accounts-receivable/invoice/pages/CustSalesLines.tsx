import React, { useState } from 'react';
import { Alert, Box, Tab, Tabs, Typography } from '@mui/material';
import { useQuery } from '@tanstack/react-query';
import { useParams } from 'react-router-dom';
import { useAuth } from '@core/auth/useAuth';
import { useCompanyStore } from '@core/company/useCompanyStore';
import { useAppTranslation } from '@core/localization/useAppTranslation';
import { PERMISSIONS } from '@core/permissions/permissions';
import { SimpleListPage } from '@patterns/simple-list/SimpleListPage';
import type { ColumnDef } from '@shared/components/data-grid/types';
import { custSalesLinesApi, type CustSalesLine } from '../api/custSalesLinesApi';

type Row = CustSalesLine & { id: string };
const tabs = [
  'overview',
  'general',
  'salesOrder',
  'priceDiscount',
  'salesTax',
  'financialDimensions',
] as const;
type TabId = (typeof tabs)[number];
type Group = { title: string; fields: (keyof CustSalesLine)[] };
const groups: Record<Exclude<TabId, 'overview'>, Group[]> = {
  general: [
    { title: 'item', fields: ['itemId', 'name'] },
    { title: 'invoice', fields: ['invoiceId', 'invoiceDate', 'salesId'] },
    { title: 'posting', fields: ['mainAccountValue'] },
    { title: 'weight', fields: ['weight'] },
  ],
  salesOrder: [
    {
      title: 'orderLines',
      fields: ['salesId', 'lineNum', 'name', 'lineHeader', 'currencyCode', 'salesGroup', 'dlvDate'],
    },
  ],
  priceDiscount: [
    {
      title: 'salesQuantity',
      fields: [
        'qty',
        'qtyPhysical',
        'inventQty',
        'remainBefore',
        'remain',
        'salesUnit',
        'partDelivery',
      ],
    },
    { title: 'price', fields: ['salesPrice', 'salesMarkup', 'priceUnit'] },
    {
      title: 'discount',
      fields: [
        'linePercent',
        'lineDisc',
        'discPercent',
        'discAmount',
        'multiLnPercent',
        'multiLnDisc',
        'sumLineDisc',
      ],
    },
    { title: 'commission', fields: ['commissCalc', 'commissAmountCur', 'commissAmountMst'] },
    { title: 'amount', fields: ['lineAmount', 'olapCostValue'] },
  ],
  salesTax: [
    {
      title: 'salesTax',
      fields: [
        'taxAutoGenerated',
        'taxGroup',
        'taxItemGroup',
        'taxAmount',
        'taxWriteCode',
        'overrideSalesTax',
        'taxAmountMst',
      ],
    },
  ],
  financialDimensions: [
    {
      title: 'financialDimensions',
      fields: [
        'businessUnitValue',
        'costCenterValue',
        'departmentValue',
        'divisionValue',
        'projectValue',
        'serviceLineValue',
      ],
    },
  ],
};
const date = (value: string) => (value && !value.startsWith('0001-') ? value.slice(0, 10) : '');

export function CustSalesLines(): React.ReactElement {
  const { accountNum = '' } = useParams<{ accountNum: string }>();
  const company = useCompanyStore((state) => state.currentCompany);
  // Reset tabs and selection when customer/company context changes.
  return (
    <CustomerLines key={`${company}:${accountNum}`} accountNum={accountNum} company={company} />
  );
}

function CustomerLines({
  accountNum,
  company,
}: {
  accountNum: string;
  company: string;
}): React.ReactElement {
  const { hasPermission } = useAuth();
  const permitted = hasPermission(PERMISSIONS.SALES_ORDER_VIEW);
  const { t, isRtl } = useAppTranslation();
  const [tab, setTab] = useState<TabId>('overview');
  const query = useQuery({
    queryKey: ['cust-sales-lines', company, accountNum],
    queryFn: ({ signal }) => custSalesLinesApi.load(accountNum, signal),
    enabled: permitted && Boolean(company && accountNum),
  });
  if (!permitted) return <Alert severity="warning">{t('partyBalance.accessDenied')}</Alert>;
  if (!accountNum) return <Alert severity="error">{t('partyBalance.accountRequired')}</Alert>;
  const number = new Intl.NumberFormat(isRtl ? 'ar-SA' : 'en-US', {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  });
  const label = (field: string) => t(`custSalesLines.fields.${field}`);
  const format = (row: Row, field: keyof CustSalesLine): string => {
    const value = row[field];
    if (value == null || value === '') return '—';
    if (typeof value === 'boolean') return t(value ? 'custSalesLines.yes' : 'custSalesLines.no');
    if (typeof value === 'number') return number.format(value);
    return field === 'invoiceDate' || field === 'dlvDate' ? date(value) || '—' : value;
  };
  const columns: ColumnDef<Row>[] = [
    {
      field: 'invoiceDate',
      headerName: label('invoiceDate'),
      width: 140,
      valueGetter: ({ row }) => date(row.invoiceDate),
    },
    {
      preview: { entity: 'releasedProduct' },
      field: 'itemId',
      headerName: label('itemId'),
      width: 170,
    },
    ...(['qty', 'salesPrice', 'linePercent', 'lineDisc', 'lineAmount'] as const).map((field) => ({
      field,
      headerName: label(field),
      width: 135,
      align: 'right' as const,
      renderCell: ({ row }: { row: Row }) => number.format(row[field]),
    })),
    {
      preview: { entity: 'customer' },
      field: 'customerAccount',
      headerName: label('customerAccount'),
      width: 170,
    },
  ];
  return (
    <SimpleListPage<Row>
      title={t('custSalesLines.title')}
      recordTableName="CustInvoiceTrans"
      enterpriseConfig={{
        readOnly: true,
        initialSelection: 'first',
        contextLabel: `${t('custSalesLines.title')} | ${accountNum}${query.data?.customerName ? ` : ${query.data.customerName}` : ''}`,
        getAuditRecordId: (row) => row.recId,
      }}
      columns={columns}
      dataSource={{
        type: 'controlled',
        rows: (query.data?.lines ?? []).map((row) => ({ ...row, id: String(row.recId) })),
        refresh: () => void query.refetch(),
      }}
      loading={query.isFetching}
      error={query.isError ? query.error.message : null}
      onRetry={() => void query.refetch()}
      filterBar={
        <Tabs
          value={tab}
          onChange={(_, value: TabId) => setTab(value)}
          variant="scrollable"
          scrollButtons="auto"
          aria-label={t('custSalesLines.views')}
          sx={{ mx: { xs: 1, sm: 2.5 }, mb: 1 }}
        >
          {tabs.map((id) => (
            <Tab
              key={id}
              id={`cust-sales-lines-tab-${id}`}
              aria-controls="cust-sales-lines-panel"
              value={id}
              label={t(`custSalesLines.tabs.${id}`)}
            />
          ))}
        </Tabs>
      }
      dataGridProps={{
        storageKey: 'accounts-receivable.cust-sales-lines',
        onRowDoubleClick: () => setTab('general'),
      }}
      detailContent={
        tab === 'overview'
          ? undefined
          : (row) => (
              <Box
                role="tabpanel"
                id="cust-sales-lines-panel"
                aria-labelledby={`cust-sales-lines-tab-${tab}`}
                sx={{ height: '100%', overflow: 'auto', py: 1.5 }}
              >
                {!row ? (
                  <Typography>{t('custSalesLines.selectLine')}</Typography>
                ) : (
                  <Box sx={{ display: 'flex', flexWrap: 'wrap', alignItems: 'flex-start', gap: 3 }}>
                    {groups[tab].map((group) => (
                      <Box
                        component="section"
                        key={group.title}
                        sx={{
                          minWidth: 170,
                          maxWidth:
                            tab === 'salesTax' || tab === 'financialDimensions'
                              ? 'none'
                              : tab === 'salesOrder'
                                ? 360
                                : 300,
                          flex:
                            tab === 'salesTax' || tab === 'financialDimensions'
                              ? '1 1 100%'
                              : undefined,
                        }}
                      >
                        <Typography variant="overline" component="h2">
                          {t(`custSalesLines.groups.${group.title}`)}
                        </Typography>
                        <Box
                          component="dl"
                          sx={{
                            m: 0,
                            display: 'grid',
                            gridTemplateColumns:
                              tab === 'salesTax' || tab === 'financialDimensions'
                                ? 'repeat(auto-fit, minmax(160px, 220px))'
                                : '1fr',
                            gap: 1.5,
                          }}
                        >
                          {group.fields.map((field) => (
                            <Box key={field}>
                              <Typography component="dt" variant="caption" color="text.secondary">
                                {label(field)}
                              </Typography>
                              <Typography
                                component="dd"
                                variant="body2"
                                sx={{
                                  m: 0,
                                  minHeight: 28,
                                  py: 0.5,
                                  borderBottom: 1,
                                  borderColor: 'divider',
                                  whiteSpace: 'pre-wrap',
                                  overflowWrap: 'anywhere',
                                  textAlign: typeof row[field] === 'number' ? 'end' : 'start',
                                }}
                              >
                                {format(row, field)}
                              </Typography>
                            </Box>
                          ))}
                        </Box>
                      </Box>
                    ))}
                  </Box>
                )}
              </Box>
            )
      }
    />
  );
}
