export interface CustSalesLinesResult {
  accountNum: string;
  customerName: string;
  lines: CustSalesLine[];
}
export const custSalesLinesApi = {
  async load(accountNum: string, signal?: AbortSignal): Promise<CustSalesLinesResult> {
    if (!accountNum.trim()) throw new ApiError('A customer account is required.', 400);
    const { data } = await apiClient.get<ApiResponse<CustSalesLinesResult>>(
      '/v1/CustInvoiceTrans/customer-lines',
      { params: { accountNum }, signal }
    );
    if (!data.success || !data.data)
      throw new ApiError(data.message || 'Unable to load customer order lines.', 500);
    return data.data;
  },
};
