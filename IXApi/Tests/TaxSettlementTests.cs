    [Fact]
    public async Task Missing_setup_and_an_empty_interval_are_refused_with_a_reason()
    {
        await using var connection = new SqliteConnection("Data Source=:memory:");
        await connection.OpenAsync();
        await using var db = await NewContextAsync(connection);
        await db.SaveChangesAsync();
        db.ChangeTracker.Clear();

        // Nothing to settle.
        var (_, empty) = await NewService(db).SettleAndPostAsync(
            new TaxSettlementInputDto("MONTHLY", new DateOnly(2026, 6, 1), new DateOnly(2026, 6, 30)), default);
        Assert.Contains("No unsettled sales tax", empty);

        // Unknown period, and a known period with no such interval.
        var (_, unknown) = await NewService(db).SettleAndPostAsync(
            new TaxSettlementInputDto("WEEKLY", new DateOnly(2026, 6, 1), new DateOnly(2026, 6, 30)), default);
        Assert.Contains("was not found", unknown);
        var (_, noInterval) = await NewService(db).SettleAndPostAsync(
            new TaxSettlementInputDto("MONTHLY", new DateOnly(2026, 9, 1), new DateOnly(2026, 9, 30)), default);
        Assert.Contains("no interval starting", noInterval);

        // The settlement date cannot precede the end of the interval being settled.
        AddTax(db, 1, "VAT-OUT", TaxDirection.Outgoing, new DateTime(2026, 6, 5), -1000m);
        await db.SaveChangesAsync();
        db.ChangeTracker.Clear();
        var (_, early) = await NewService(db).SettleAndPostAsync(
            new TaxSettlementInputDto("MONTHLY", new DateOnly(2026, 6, 1), new DateOnly(2026, 6, 15)), default);
        Assert.Contains("must not precede the end of the interval", early);
    }

