// =========================================================================
// Structural mask patterns — common presets a user can click to apply
// Syntax: 0 = digit, a = letter, * = any character
// validationType: links this mask to a validation rule type (auto-creates rule on click)
// regex: the server-side validation expression that enforces the mask's structure
// =========================================================================
interface MaskPattern { label: string; mask: string; validationType?: string; regex?: string; }

